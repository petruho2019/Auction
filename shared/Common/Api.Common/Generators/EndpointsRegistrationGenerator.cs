using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Api.Common.Generators;

[Generator]
public class EndpointsRegistrationGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var candidates = context.SyntaxProvider.CreateSyntaxProvider(
            static (node, _) => node is TypeDeclarationSyntax,

            static (syntaxContext, _) =>
            syntaxContext.SemanticModel.GetDeclaredSymbol(
                (TypeDeclarationSyntax)syntaxContext.Node) as INamedTypeSymbol
            )
            .Where(static symbol => symbol is not null)
            .Collect();

        var input = context.CompilationProvider.Combine(candidates);

        context.RegisterSourceOutput(
            input,
            static (productionContext, source) =>
            {
                var compilation = source.Left;
                var candidates = source.Right;

                var interfaceSymbol =
                    compilation.GetTypeByMetadataName(
                        "Api.Common.Data.Interfaces.IEndpoint");

                if (interfaceSymbol is null)
                {
                    return;
                }

                var types = new List<INamedTypeSymbol>();
                var seen = new HashSet<string>(
                    StringComparer.Ordinal);

                foreach (var candidate in candidates)
                {
                    if (candidate is null)
                        continue;

                    // Оставляем только конкретные классы.
                    if (candidate.TypeKind != TypeKind.Class ||
                        candidate.IsAbstract ||
                        candidate.Arity != 0)
                    {
                        continue;
                    }

                    // Проверяем интерфейс с учётом наследования.
                    bool implementsInterface =
                        candidate.AllInterfaces.Any(i =>
                            SymbolEqualityComparer.Default.Equals(
                                i,
                                interfaceSymbol));

                    if (!implementsInterface)
                        continue;

                    // Частичный класс может встретиться несколько раз.
                    string typeName = candidate.ToDisplayString(
                        SymbolDisplayFormat.FullyQualifiedFormat);

                    if (seen.Add(typeName))
                        types.Add(candidate);
                }

                var entries = string.Join(
                    "\n",
                    types.Select(type =>
                        $"            group.Register<{type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)}>();"));

                string generatedCode = $$"""
                    // <auto-generated/>
                    using Api.Common.Extensions;
                    using Microsoft.AspNetCore.Routing;

                    namespace Api.Common.Extensions;

                    public static class EndpointsRegistry
                    {
                        public static RouteGroupBuilder MapEndpoints(
                            this RouteGroupBuilder group)
                        {
                    {{entries}}
                                return group;
                        }
                    }
                    """;

                productionContext.AddSource(
                    "EndpointsRegistry.g.cs",
                    SourceText.From(
                        generatedCode,
                        Encoding.UTF8));
            });

    }
}